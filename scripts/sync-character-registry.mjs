import { readdir, readFile, writeFile } from 'node:fs/promises';
const directory = new URL('../characters/active/', import.meta.url);
const files = (await readdir(directory)).filter((name) => name.endsWith('.json')).sort();
const imports = [],
  entries = [];
for (const [index, file] of files.entries()) {
  const sheet = JSON.parse(await readFile(new URL(file, directory), 'utf8'));
  if (sheet.status !== 'active' || file !== sheet.id + '.json')
    throw Error(`Invalid active sheet: ${file}`);
  imports.push(`import sheet${index} from '../characters/active/${file}' with {type:'json'};`);
  entries.push(`  ${JSON.stringify(sheet.id)}:sheet${index},`);
}
await writeFile(
  new URL('../src/character-sheets.mjs', import.meta.url),
  `// Generated by npm run sync:characters. Edit characters/active/*.json, not this registry.\n${imports.join('\n')}\nexport const characterSheets={\n${entries.join('\n')}\n};\n`,
);
console.log(
  `Registered ${files.length} active character sheets; proposed sheets stay outside the app bundle.`,
);
