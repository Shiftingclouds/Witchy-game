// Extract the storyteller's style reference from the authored story exports (story/*.md).
// Usage: node scripts/make-style-samples.mjs  → writes src/ai/world/style.mjs
import { readdirSync, readFileSync, writeFileSync } from 'node:fs';
import { characterSheets } from '../src/character-sheets.mjs';

const byName = Object.fromEntries(
  Object.entries(characterSheets).map(([id, sheet]) => [sheet.identity.name, id]),
);
const files = readdirSync('story')
  .filter((f) => /^0[1-8]-.*\.md$/.test(f))
  .sort();
const narration = [];
const voices = {};
for (const file of files) {
  for (const raw of readFileSync('story/' + file, 'utf8').split(/\r?\n/)) {
    const line = raw.trim();
    const speech = line.match(/^\*\*(.+?) \([a-z-]+\):\*\* (.+)$/);
    if (speech) {
      const id = byName[speech[1]];
      if (id) (voices[id] ||= []).push(speech[2]);
      continue;
    }
    if (!line || /^[#>*|-]|^Generated|^Chapter /.test(line)) continue;
    const words = line.split(/\s+/).length;
    if (words >= 35 && words <= 90) narration.push(line);
  }
}
const spread = (list, n) =>
  list.length <= n
    ? list
    : Array.from({ length: n }, (_, i) => list[Math.floor((i * list.length) / n)]);
const samples = {
  narration: spread(narration, 8),
  voices: Object.fromEntries(
    Object.entries(voices)
      .filter(([, lines]) => lines.length >= 2)
      .map(([id, lines]) => [
        id,
        spread(
          lines.filter((l) => l.length <= 260),
          4,
        ),
      ]),
  ),
};
writeFileSync(
  'src/ai/world/style.mjs',
  `// Generated by scripts/make-style-samples.mjs from the authored story. Do not edit by hand.\n` +
    `// The storyteller matches this voice and quality.\nexport const STYLE_SAMPLES = ${JSON.stringify(samples, null, 2)};\n`,
);
console.log(
  `${samples.narration.length} narration samples, ${Object.keys(samples.voices).length} character voices.`,
);
