// Import a ChatGPT story reply into the game.
// Usage: npm run import:story -- story-drafts/<file> [--check]
// Writes src/story/chapters/<NN>-<scene>.mjs only when the reply keeps every section, decision,
// option and branch of the scene it replaces. --check validates without writing.
import { readFileSync, readdirSync, writeFileSync as writeRaw, mkdirSync } from 'node:fs';
import * as prettier from 'prettier';
import { characters, expressions, locations, storyPlaces } from '../src/content.mjs';
import { stagedScenes } from '../src/scene-beats.mjs';
import { parseStoryScript, compareStructure, mergeMetadata } from './story-parse.mjs';

// Generated files follow the project's formatting, so \`npm run check\` accepts them.
async function writeFileSync(path, text) {
  const config = (await prettier.resolveConfig(path)) || {};
  writeRaw(path, await prettier.format(text, { ...config, filepath: path }));
}

const [file, ...flags] = process.argv.slice(2);
if (!file) {
  console.error('Usage: npm run import:story -- story-drafts/<file> [--check]');
  process.exit(2);
}
const check = flags.includes('--check');
const nameToId = Object.fromEntries(characters.map((c) => [c.name, c.id]));
const allowedEmotions = Object.fromEntries(
  characters.map((c) => [c.id, expressions[c.id] || ['neutral']]),
);
const { scene, exits, errors, warnings } = parseStoryScript(readFileSync(file, 'utf8'), {
  nameToId,
  allowedEmotions,
});
const current = scene && stagedScenes.find((s) => s.id === scene.id);
if (scene && !current) errors.push(`The game has no scene "${scene.id}" to replace.`);
if (scene && current) {
  if (current.chapter !== scene.chapter)
    errors.push(`Scene ${scene.id} is chapter ${current.chapter}, not ${scene.chapter}.`);
  errors.push(...compareStructure(current, scene));
  const places = new Set([...locations, ...storyPlaces].map((l) => l.id));
  for (const b of scene.beats)
    if (!places.has(b.section.location))
      errors.push(`SECTION ${b.section.id}: unknown place "${b.section.location}"`);
}
for (const w of [...new Set(warnings)]) console.warn('note: ' + w);
if (errors.length) {
  console.error(`Not imported. ${errors.length} problem(s) to send back to ChatGPT:`);
  for (const e of [...new Set(errors)]) console.error(' - ' + e);
  process.exit(1);
}
const merged = mergeMetadata(current, scene);
const decisions = merged.beats.filter((b) => b.choice).length;
const sections = new Set(merged.beats.map((b) => b.section.id)).size;
if (check) {
  console.log(
    `OK: ${scene.id} would import cleanly (${sections} sections, ${decisions} decisions).`,
  );
  process.exit(0);
}
mkdirSync('src/story/chapters', { recursive: true });
const name = `${String(scene.chapter).padStart(2, '0')}-${scene.id}.mjs`;
await writeFileSync(
  `src/story/chapters/${name}`,
  `// Imported from ${file.replace(/\\/g, '/')} by \`npm run import:story\`. Prose by ChatGPT; do not edit by hand —
// change the draft and import again.
export default ${JSON.stringify({ scene: merged, exits: exits.filter(Boolean).length ? exits : null }, null, 2)};
`,
);
const files = readdirSync('src/story/chapters')
  .filter((f) => /^\d\d-.+\.mjs$/.test(f))
  .sort();
await writeFileSync(
  'src/story/chapters/index.mjs',
  `// Chapters imported from ChatGPT's rewrite (generated by \`npm run import:story\`).
${files.map((f, i) => `import c${i} from './${f}';`).join('\n')}

export const importedChapters = [${files.map((_, i) => `c${i}`).join(', ')}];
`,
);
console.log(
  `Imported chapter ${scene.chapter} (${scene.id}): ${sections} sections, ${decisions} decisions → src/story/chapters/${name}`,
);
